const compiled = (pattern: string, mode: 'path' | 'name' = 'path') => {
  const glob = mode === 'name' ? compileGlob(pattern, 'name') : compileGlob(pattern);
  if (glob.kind !== 'compiled') throw new Error(`${pattern} was refused: ${glob.unsupported}`);
  return glob;
};

const metered = (pattern: string, input: string, mode: 'path' | 'name' = 'path'): { matched: boolean; steps: number; bound: number } => {
  const glob = compiled(pattern, mode);
  const meter: GlobMeter = { steps: 0 };
  const matched = glob.matches(input, meter);
  return { matched, steps: meter.steps, bound: glob.stepBound(input) };
};

describe('the product glob language', () => {
  it('matches every ordinary glob exactly as picomatch 4.0.7 with dot: true did', () => {
    expect(PICOMATCH_DOT_TRUE.length).toBeGreaterThanOrEqual(150);
    const differing = PICOMATCH_DOT_TRUE.filter(([pattern, input, matched]) => compiled(pattern).matches(input) !== matched);
    expect(differing).toEqual([]);
  });

  it('negates a bracket class that opens the pattern, where picomatch read [! there as a literal !', () => {
    const glob = compiled('[!a-c].ts');
    expect(['x.ts', 'd.ts', '-.ts'].map((input) => glob.matches(input))).toEqual([true, true, true]);
    expect(['a.ts', 'b.ts', '!.ts'].map((input) => glob.matches(input))).toEqual([false, false, true]);
  });

  it('never matches the . and .. segments with a star, in every position, where picomatch let .* match .. only at the start', () => {
    expect([compiled('.*').matches('..'), compiled('x/.*').matches('x/..'), compiled('**').matches('a/../b'), compiled('?').matches('.')]).toEqual([false, false, false, true]);
  });

  const REFUSED: readonly (readonly [pattern: string, construct: GlobRefusal])[] = [
    ['+(a)+(a)+(a)', 'extglob'],
    ['+(a)+(a)+(a)+(a)+(a)+(a)+(a)+(a)+(a)+(a)+(a)+(a)b', 'extglob'],
    ['*(a|b)*(a|b)*(a|b)', 'extglob'],
    ['@(+(a))', 'extglob'],
    ['?(a)', 'extglob'],
    ['!(a)', 'extglob'],
    ['**/+(a)/**/*.ts', 'extglob'],
    ['((a)+)+b', 'group'],
    ['(a|a)+b', 'group'],
    ['(?:a+)+', 'group'],
    ['a|b', 'group'],
    ['{a,{a,b}+}+', 'setQuantifier'],
    ['{a,b}+', 'setQuantifier'],
    ['[a]+', 'setQuantifier'],
    ['!a/**', 'negation'],
    ['a**b', 'innerGlobstar'],
    ['**.ts', 'innerGlobstar'],
    ['{1..9}', 'braceRange'],
    ['[[:alpha:]]', 'className'],
    ['{a,{b,{c,{d,{e,f}}}}}', 'braceDepth'],
    ['{a,b}{a,b}{a,b}{a,b}{a,b}{a,b}{a,b}{a,b}{a,b}', 'expansions'],
    ['a'.repeat(MAX_GLOB_PATTERN_LENGTH + 1), 'length'],
  ];

  it.each(REFUSED)('refuses %s naming the unsupported construct', (pattern, construct) => {
    expect(compileGlob(pattern)).toEqual({ kind: 'refused', construct, unsupported: GLOB_REFUSALS[construct] });
  });

  it('accepts the deepest and the widest brace sets its constants allow', () => {
    expect(compiled('{a,{b,{c,{d,e}}}}').matches('e')).toBe(true);
    expect(MAX_GLOB_BRACE_DEPTH).toBe(4);
    expect(compiled('{a,b}{a,b}{a,b}{a,b}{a,b}{a,b}{a,b}{a,b}').matches('abababab')).toBe(true);
    expect(MAX_GLOB_EXPANSIONS).toBe(256);
    expect(compiled('a'.repeat(MAX_GLOB_PATTERN_LENGTH)).matches('a'.repeat(MAX_GLOB_PATTERN_LENGTH))).toBe(true);
  });

  it.each([
    ['a*a*a*a*a*a*a*a*a*a*a*a*b', 'a'.repeat(40)],
    ['*?*?*?*?*?*?*?*?x', 'y'.repeat(60)],
    ['**/**/**/**/**/**/**/**/**/**/b', 'a/'.repeat(30) + 'c'],
    ['**/a/**/a/**/a/**/a/**/b', 'a/'.repeat(30) + 'c'],
    [`{${Array.from({ length: 200 }, (_, index) => `n${index}`).join(',')}}/**/*.ts`, 'x/'.repeat(20) + 'y.js'],
    ['{a,b}{a,b}{a,b}{a,b}{a,b}{a,b}{a,b}{a,b}*c', 'ab'.repeat(40)],
    ['[a-z]*[a-z]*[a-z]*[a-z]*[a-z]*0', 'q'.repeat(80)],
  ])('matches the adversarial %s within its step bound', (pattern, input) => {
    const { matched, steps, bound } = metered(pattern, input);
    expect(matched).toBe(false);
    expect(steps).toBeGreaterThan(0);
    expect(steps).toBeLessThanOrEqual(bound);
  });

  it('states a bound that grows with the product of the pattern and input lengths, not exponentially', () => {
    const glob = compiled('a*a*a*b');
    expect(glob.stepBound('a'.repeat(10))).toBe(2 * 1 * (7 + 2) * (10 + 2));
  });
});

describe('the name form of the glob language', () => {
  it('reads * as any run of characters and every other character literally', () => {
    expect(['MYCO_PRIMARY', 'MYCO_', 'XMYCO_A'].map((name) => compiled('MYCO_*', 'name').matches(name))).toEqual([true, true, false]);
    expect(compiled('A(B)|C+[D]?*', 'name').matches('A(B)|C+[D]?zz')).toBe(true);
    expect(compiled('A?', 'name').matches('AB')).toBe(false);
    expect(compiled('*', 'name').matches('a/b.c')).toBe(true);
  });

  it('matches an adversarial name pattern within its step bound', () => {
    const { matched, steps, bound } = metered('A*A*A*A*A*A*A*A*A*A*A*A*B', 'A'.repeat(64), 'name');
    expect(matched).toBe(false);
    expect(steps).toBeLessThanOrEqual(bound);
  });
});
