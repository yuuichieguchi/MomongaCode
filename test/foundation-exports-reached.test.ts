describe('every export of the foundation index is reached by a product package', () => {
  const exported = exportedNames(INDEX);
  const product = namesTakenBy(productFilesOutside('foundation'), MODULE);
  const tests = namesTakenBy(testFiles(), MODULE);
  const unreached = exported.filter((name) => !product.has(name));

  it('exports each name once', () => {
    expect(exported.filter((name, index) => exported.indexOf(name) !== index)).toEqual([]);
  });

  it('exports nothing that no product package and no test names', () => {
    expect(unreached.filter((name) => !tests.has(name))).toEqual([]);
  });

  it('exports nothing that only tests name, apart from the listed present names', () => {
    expect(unreached.filter((name) => tests.has(name))).toEqual(NAMED_ONLY_BY_TESTS);
  });
});
